/// App language (Arabic or English) and the translated strings.
class Lang extends ValueNotifier<String> {
  Lang(super.code);

  bool get isAr => value == 'ar';
}

final lang = Lang('ar');

String tr(String key) => (_strings[lang.value] ?? _strings['en']!)[key] ?? _strings['en']![key] ?? key;

/// Fills `{0}`, `{1}` … placeholders.
String trf(String key, List<Object> args) {
  var s = tr(key);
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  return s;
}

